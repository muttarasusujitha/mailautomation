"""Course-outline structure for curriculum modules (SpringXE-style delivery content).

A module outline holds what a client-facing course outline shows:

    {
      "topic_groups": [{"heading": "Evidence-First Prompting", "lead": "",
                        "items": [{"text": "Separating:", "children": ["Confirmed facts", "Assumptions"]}]}],
      "principle": {"title": "Engineering Principle", "lead": "A professional workflow starts with:",
                    "points": ["Understanding the repository.", "Establishing the baseline."]},
      "lab": {"title": "Repository X-Ray", "scenario": "Participants receive an unfamiliar repository.",
              "lead": "Codex must identify:", "tasks": ["Entry points", "Build commands"],
              "verify": ["The analyst cannot modify files."], "deliverables": ["Architecture summary"]},
      "assessment": "",
      "source": "reference" | "model_draft" | "derived",
    }

Stored outlines come from imported reference course outlines or model drafts.
Datasets without one get an outline derived at render time from their flat
fields, with template and padding text left out so the client never sees it.

No third-party imports, so this module can be tested in isolation.
"""

from __future__ import annotations

import re
from typing import Any, Dict, Iterable, List, Optional

OUTLINE_VERSION = "course-outline-v1"

# Filler written into datasets by earlier enrichment passes, and padding the
# template generator adds when a day has few subtopics. Never client content.
_TEMPLATE_TEXT = re.compile(
    r"^Demonstrate '.*' on a prepared training sample"
    r"|^Participant submission for '"
    r"|^Reproduce the source lab:"
    r"|^Reproduce the submitted participant output"
    r"|^Complete and demonstrate:"
    r"|^Explain how the lab applies "
    r"|^Explain the .{1,80} concepts in the context of "
    r"|^Configure or implement the key .{1,60} features covered"
    r"|^Complete the hands-on lab and validate"
    r"|^Identify common implementation mistakes and troubleshooting"
    r"|^Explain the design choices and operational purpose of "
    r"|^Validate the implementation, diagnose a realistic failure"
    r"|^Relate the deliverable to acceptance criteria"
    r"|^Demonstrate .{1,120} through the participant output"
    r"|^Demonstrate .{1,120} using the training sample\.?$"
    r"|^Using a trainer-provided sample, complete "
    r"|: completed lab artefact, execution notes and validation evidence\.?$"
    r"|^Review the submitted .{1,120} artefact against:"
    r"|^A team must demonstrate .{1,120} on a representative sample"
    r"|^Configure, implement, validate, and troubleshoot .{1,120}; submit working output"
    r"|^Implement and validate .{1,80}; capture evidence and troubleshoot"
    r"|^Apply .{1,80} through guided practice\.?$"
    r"|^Trainer verifies: "
    r"|generated by the Training TOC Agent"
    r"|^Working knowledge of the core concepts and standard workflows used in "
    r"|^Prior hands-on exposure to .{1,80} or equivalent project experience"
    r"|^Apply this to the '.{1,120}' lab result and record what happens",
    re.IGNORECASE,
)
_FILLER_SUBTOPIC = re.compile(
    r"terminology and feature mapping for this topic"
    r"|configuration and implementation considerations$"
    r"|best practices and common mistakes for this topic"
    r"|^(?:terminology and scope|key components and responsibilities|configuration or workflow steps"
    r"|implementation approach|integration considerations|hands-on use case|validation and testing"
    r"|common mistakes and edge cases|troubleshooting approach|industry best practices"
    r"|review questions and applied assessment|implementation workflow|input and output validation"
    r"|common errors and edge cases|debugging techniques|testing and maintainability practices"
    r"|worked example|guided coding practice|review questions)$"
    r"|hands-on implementation$",
    re.IGNORECASE,
)
_GENERIC_CHECK = re.compile(
    r"meets objectives|participant completes the lab|applies the same method|recorded assessment results"
    r"|completed lab output for|describes an appropriate correction"
    r"|^the workflow completes successfully\.?$|^the case is rejected or handled according to the stated rule"
    r"|^known risks and a corrective action are documented",
    re.IGNORECASE,
)
# Imperative verbs that start a new lab step after ", " or " and " in a one-sentence lab.
_LAB_VERBS = frozenset("""
add alert analyse analyze answer apply assign audit automate block build calculate call change check choose clean collect
compare complete configure confirm connect convert create cut decide defend define delete demo demonstrate deploy design
detect document draw enable enforce estimate evaluate explain explore export extend fix find generate give handle identify
implement import install integrate investigate isolate keep link list load log map measure migrate model monitor move
note open package parse prepare present produce prove publish query raise read rebuild recommend record refactor register
release remove render replace report reproduce restore restrict retry review roll route run save schedule search secure
send set share show sign simulate sketch split store submit summarise summarize take tag test trace track train trigger
tune turn update upgrade upload use validate verify visualise visualize write
""".split())
_LAB_SPLIT = re.compile(r",\s+(?:and\s+|then\s+)?|;\s+|\s+and\s+(?:then\s+)?|\s+then\s+")


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, dict):
        return _text(value.get("text") or value.get("topic") or value.get("title") or value.get("name"))
    return re.sub(r"\s+", " ", str(value)).strip()


def _list(value: Any) -> List[Any]:
    if value in (None, ""):
        return []
    return list(value) if isinstance(value, (list, tuple, set)) else [value]


def is_template_text(value: Any) -> bool:
    text = _text(value)
    return bool(text) and bool(_TEMPLATE_TEXT.search(text))


def is_filler_subtopic(value: Any) -> bool:
    text = _text(value)
    return bool(text) and bool(_FILLER_SUBTOPIC.search(text))


def real_text(value: Any) -> str:
    """The value, or '' when it is template or padding text."""
    text = _text(value)
    return "" if is_template_text(text) else text


def clean_subtopics(subtopics: Iterable[Any], drop: Iterable[str] = ()) -> List[Any]:
    """Remove filler, repeats and the given items; keep dict items and order."""
    dropped = {item.lower() for item in drop}
    seen, result = set(), []
    for item in subtopics or []:
        text = _text(item)
        key = text.lower()
        if not text or key in seen or key in dropped or is_filler_subtopic(text):
            continue
        seen.add(key)
        result.append(item)
    return result


def repeated_items(days: List[Dict[str, Any]], share: float = 0.6) -> Dict[str, int]:
    """Subtopics copied onto most days of a course, mapped to the first day index using them."""
    if len(days) < 4:
        return {}
    counts: Dict[str, int] = {}
    first: Dict[str, int] = {}
    for index, day in enumerate(days):
        for item in {(_text(value)).lower() for value in _list(day.get("subtopics")) if _text(value)}:
            counts[item] = counts.get(item, 0) + 1
            first.setdefault(item, index)
    return {item: first[item] for item, count in counts.items() if count >= max(4, share * len(days))}


# --------------------------------------------------------------------------- derived outlines

def _split_item(value: Any) -> Dict[str, Any]:
    if isinstance(value, dict):
        children = [_text(child) for child in _list(value.get("children") or value.get("items") or value.get("subtopics"))]
        return {"text": _text(value), "children": [child for child in children if child]}
    text = _text(value)
    match = re.match(r"^([^:]{3,60}):\s*(.+)$", text)
    if match:
        children = [part.strip(" .") for part in re.split(r",\s*|;\s*", match.group(2)) if part.strip(" .")]
        if len(children) >= 3 and all(len(child) <= 60 for child in children):
            return {"text": match.group(1).strip() + ":", "children": children}
    return {"text": text, "children": []}


def lab_steps(sentence: str) -> List[str]:
    """Split "Create X, move Y and review Z." into its imperative steps."""
    sentence = sentence.strip().rstrip(".")
    splits = [(match.start(), match.end()) for match in _LAB_SPLIT.finditer(sentence)
              if (re.match(r"[a-z]+", sentence[match.end():]) or [None])[0] in _LAB_VERBS]
    # Words such as "release" or "test" are also nouns ("... and release decision"):
    # a step needs at least three words, otherwise the split is undone.
    while True:
        bounds = [0, *[end for _, end in splits]]
        ends = [*[start for start, _ in splits], len(sentence)]
        short = next((index for index in range(1, len(bounds))
                      if len(sentence[bounds[index]:ends[index]].split()) < 3), None)
        if short is None:
            break
        del splits[short - 1]
    bounds = [0, *[end for _, end in splits]]
    ends = [*[start for start, _ in splits], len(sentence)]
    steps = [sentence[a:b].strip(" ,;") for a, b in zip(bounds, ends) if sentence[a:b].strip(" ,;")]
    return [step[:1].upper() + step[1:] for step in steps]


def _empty_lab() -> Dict[str, Any]:
    return {"title": "", "scenario": "", "lead": "", "tasks": [], "verify": [], "deliverables": []}


def _lab_from_text(lab: str) -> Dict[str, Any]:
    lab = real_text(lab)
    result = _empty_lab()
    if not lab:
        return result
    lines = [line.strip(" \u2022-") for line in re.split(r"\n+", lab) if line.strip(" \u2022-")]
    if len(lines) > 1:
        result.update(title=lines[0].rstrip(".:"), tasks=lines[1:])
        return result
    tasks = [step for sentence in re.split(r"(?<=[.;])\s+", lab) if sentence.strip()
             for step in lab_steps(sentence)]
    if len(tasks) >= 2:
        result["tasks"] = tasks  # the renderer names the lab after its module
    elif len(lab) <= 90:
        result["title"] = lab.rstrip(".")
    else:
        result["scenario"] = lab
    return result


def check_statement(condition: Any, expected: Any) -> str:
    """'Delete one pod' + 'A replacement pod is created.' -> 'Delete one pod \u2013 A replacement pod is created.'"""
    condition, expected = _text(condition).rstrip(" .:"), _text(expected)
    if not condition or not expected:
        return expected or condition
    return f"{condition} \u2013 {expected}"


def _checks(value: Any) -> List[str]:
    result = []
    for check in _list(value):
        if isinstance(check, dict):
            text = check_statement(check.get("input_or_condition"), check.get("expected_result"))
        elif isinstance(check, (list, tuple)) and len(check) >= 2:
            text = check_statement(check[0], check[1])
        else:
            text = _text(check)
        if text and not _GENERIC_CHECK.search(text) and not is_template_text(text):
            result.append(text if text.endswith((".", "?", "!")) else text + ".")
    return list(dict.fromkeys(result))[:6]


def roadmap_groups(roadmap: Any) -> List[Dict[str, Any]]:
    """[{"stage": "Understand", "subtopics": [...]}, ...] -> headed topic groups "Step 1: Understand"."""
    groups = []
    for step in _list(roadmap):
        if not isinstance(step, dict):
            continue
        items = [_split_item(item) for item in clean_subtopics(_list(step.get("subtopics")))]
        items = [item for item in items if item["text"]]
        stage = _text(step.get("stage"))
        if stage and items:
            groups.append({"heading": f"Step {len(groups) + 1}: {stage}", "lead": "", "items": items})
    return groups


def outline_from_flat(row: Dict[str, Any]) -> Dict[str, Any]:
    """Build an outline from a day or module's flat fields, skipping template text."""
    stored = row.get("outline")
    if isinstance(stored, dict) and (stored.get("topic_groups") or (stored.get("lab") or {}).get("title")):
        return stored
    items = [_split_item(item) for item in clean_subtopics(_list(row.get("subtopics")))]
    items = [item for item in items if item["text"]]
    groups = roadmap_groups(row.get("roadmap"))
    lab = _lab_from_text(row.get("lab") or row.get("lab_task") or "")
    scenario = real_text(row.get("scenario"))
    if scenario and not lab["scenario"]:
        lab["scenario"] = scenario
    lab["verify"] = _checks(row.get("acceptance_checks") or row.get("checks"))
    deliverable = real_text(row.get("deliverable"))
    if deliverable:
        lab["deliverables"] = [deliverable]
    return {
        "topic_groups": groups or ([{"heading": "", "lead": "", "items": items}] if items else []),
        "principle": {"title": "", "lead": "", "points": []},
        "lab": lab,
        "assessment": real_text(row.get("assessment")),
        "source": "derived",
    }


# --------------------------------------------------------------------------- reference parsing

_KNOWN_HEADINGS = {
    "skills", "hooks", "rules", "workflow", "validation", "observability", "scenario", "topics",
    "debugging topics", "testing strategies",
}
_SMALL_WORDS = {"a", "an", "and", "as", "at", "by", "for", "in", "of", "on", "or", "the", "to", "with", "vs", "versus"}


def _is_heading(line: str, next_line: str) -> bool:
    if not line or line.startswith("o ") or re.search(r"[.,;:!?\u201d\"]$", line) or next_line.startswith("o "):
        return False
    words = line.split()
    if line.lower() in _KNOWN_HEADINGS:
        return True
    if not 2 <= len(words) <= 6 or re.match(r"^\d", line):
        return False
    significant = [word for word in words if word.lower() not in _SMALL_WORDS]
    return bool(significant) and all(word[:1].isupper() or word[:1].isdigit() for word in significant)


def _join_wrapped(lines: List[str]) -> List[str]:
    joined: List[str] = []
    for line in lines:
        if joined and line[:1].islower() and not re.search(r"[.:;!?]$", joined[-1]) and not line.startswith("o "):
            joined[-1] = f"{joined[-1]} {line}"
        else:
            joined.append(line)
    return joined


def outline_from_reference(reference_text: str) -> Dict[str, Any]:
    """Parse an imported course-outline module (PDF text) into an outline."""
    raw = [line.strip() for line in str(reference_text or "").splitlines()]
    lines = _join_wrapped([line for line in raw if line and line not in {"o", "\u2022", "Topics"}])
    outline: Dict[str, Any] = {
        "topic_groups": [], "principle": {"title": "", "lead": "", "points": []},
        "lab": {"title": "", "scenario": "", "lead": "", "tasks": [], "verify": [], "deliverables": []},
        "assessment": "", "source": "reference",
    }
    section = "topics"
    group: Optional[Dict[str, Any]] = None
    assessment: List[str] = []

    def new_group(heading: str) -> Dict[str, Any]:
        created = {"heading": heading, "lead": "", "items": []}
        outline["topic_groups"].append(created)
        return created

    for index, line in enumerate(lines):
        next_line = lines[index + 1] if index + 1 < len(lines) else ""
        lab_match = re.match(r"^Lab \d+\s*[:.]\s*(.*)$", line)
        if re.match(r"^Day \d+\s*[\u2013\-]", line):
            break
        if lab_match:
            section = "lab"
            outline["lab"]["title"] = lab_match.group(1).strip()
            continue
        if line == "Lab Deliverable":
            section = "deliverable"
            continue
        if line in {"Lab Test", "Validation"} and section in {"lab", "deliverable"}:
            section = "verify"
            continue
        if re.match(r"^Day \d+ Assessment$", line):
            section = "assessment"
            continue
        if re.search(r"\bPrinciples?$", line) and len(line.split()) <= 4 and section == "topics":
            section = "principle"
            outline["principle"]["title"] = line
            continue
        if section in {"principle", "lab_scenario"} and _is_heading(line, next_line):
            section = "topics"
        if section == "topics" and line == "Scenario":
            # Integration labs open with a scenario instead of "Lab N:".
            section = "lab_scenario"
            continue
        if section == "topics" and line in {"Participant Tasks", "Required Participant Workflow"}:
            section = "lab"
            outline["lab"]["lead"] = outline["lab"]["lead"] or "Participant tasks:"
            continue
        if section == "topics":
            if _is_heading(line, next_line):
                group = new_group(line)
                continue
            if group is None:
                group = new_group("")
            if line.startswith("o "):
                if group["items"]:
                    group["items"][-1]["children"].append(line[2:].strip())
                else:
                    group["items"].append({"text": line[2:].strip(), "children": []})
            elif line.endswith(":") and not next_line.startswith("o ") and not group["items"]:
                group["lead"] = line
            else:
                group["items"].append({"text": line, "children": []})
        elif section == "principle":
            if line.endswith(":") and not outline["principle"]["points"]:
                outline["principle"]["lead"] = line
            else:
                outline["principle"]["points"].append(re.sub(r"^\d+\.\s*", "", line))
        elif section == "lab":
            lab = outline["lab"]
            quoted = next_line[:1] in {"\u201c", "\""} or len(next_line) > 60
            if line.startswith("o ") and lab["tasks"]:
                lab["tasks"][-1] += f" ({line[2:].strip()})"
            elif line.endswith(":") and not lab["tasks"] and quoted and re.search(r"[.\u201d\"]$", next_line):
                # "Original requirement:" followed by the quoted requirement is scenario text.
                lab["scenario"] = f"{lab['scenario']} {line}".strip()
            elif line.endswith(":") and not lab["tasks"]:
                lab["lead"] = line
            elif not lab["tasks"] and not lab["lead"] and re.search(r"[.\u201d\"]$", line):
                lab["scenario"] = f"{lab['scenario']} {line}".strip()
            else:
                lab["tasks"].append(re.sub(r"^\d+\.\s*", "", line))
        elif section == "lab_scenario":
            outline["lab"]["scenario"] = f"{outline['lab']['scenario']} {line}".strip()
        elif section == "verify":
            if not re.search(r"verify that:?$", line, re.IGNORECASE):
                outline["lab"]["verify"].append(line)
        elif section == "deliverable":
            outline["lab"]["deliverables"].append(line)
        elif section == "assessment":
            assessment.append(line)

    for created in outline["topic_groups"]:
        if not created["items"] and created["heading"]:
            created["items"] = []
    outline["topic_groups"] = [created for created in outline["topic_groups"] if created["items"] or created["lead"]]
    deliverables = outline["lab"]["deliverables"]
    if len(deliverables) > 1 and deliverables[0].endswith(":"):
        outline["lab"]["deliverables"] = [f"{deliverables[0]} {', '.join(deliverables[1:])}."]
    if assessment:
        lead, rest = assessment[0], assessment[1:]
        outline["assessment"] = f"{lead} {', '.join(rest)}." if lead.endswith(":") and rest else " ".join(assessment)
    return outline


def subtopics_from_outline(outline: Dict[str, Any]) -> List[str]:
    """Flat subtopic list for consumers that read ``subtopics``."""
    result = []
    for group in _list((outline or {}).get("topic_groups")):
        for item in _list(group.get("items")):
            text = _text(item).rstrip(":")
            children = [_text(child) for child in _list(item.get("children") if isinstance(item, dict) else [])]
            result.append(f"{text}: {', '.join(children)}" if children else text)
    return [item for item in result if item]


def outline_problems(outline: Dict[str, Any]) -> List[str]:
    """Structural checks for stored outlines (references and model drafts)."""
    problems = []
    groups = _list((outline or {}).get("topic_groups"))
    if not groups or not any(_list(group.get("items")) for group in groups):
        problems.append("no topics")
    lab = (outline or {}).get("lab") or {}
    if not _text(lab.get("title")):
        problems.append("no lab title")
    if len(_list(lab.get("tasks"))) < 2:
        problems.append("lab needs participant tasks")
    if not _list(lab.get("deliverables")):
        problems.append("lab needs a deliverable")
    for value in [*(_text(item) for group in groups for item in _list(group.get("items"))),
                  _text(lab.get("title")), *(_text(task) for task in _list(lab.get("tasks")))]:
        if is_template_text(value) or is_filler_subtopic(value):
            problems.append(f"template text: {value[:60]}")
    return problems


